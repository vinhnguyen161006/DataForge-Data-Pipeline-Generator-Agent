import asyncio
from typing import Any

import httpx


class MetabaseClient:
    def __init__(self, base_url: str, user: str, password: str):
        self.base_url = base_url.rstrip("/")
        self.user = user
        self.password = password
        self.token: str | None = None
        self.client = httpx.AsyncClient(timeout=30.0)

    async def __aenter__(self) -> "MetabaseClient":
        return self

    async def __aexit__(self, exc_type: Any, exc_val: Any, exc_tb: Any) -> None:
        await self.client.aclose()

    @property
    def headers(self) -> dict[str, str]:
        if not self.token:
            raise RuntimeError("Not logged in to Metabase")
        return {"Content-Type": "application/json", "X-Metabase-Session": self.token}

    async def login(self) -> None:
        response = await self.client.post(
            f"{self.base_url}/api/session", json={"username": self.user, "password": self.password}
        )
        response.raise_for_status()
        self.token = response.json().get("id")

    async def sync_database_schema(self, database_id: int) -> None:
        sync_response = await self.client.post(
            f"{self.base_url}/api/database/{database_id}/sync_schema", headers=self.headers
        )
        sync_response.raise_for_status()

        max_retries = 10
        for _ in range(max_retries):
            await asyncio.sleep(2)
            db_response = await self.client.get(
                f"{self.base_url}/api/database/{database_id}?include=tables", headers=self.headers
            )
            if db_response.status_code == 200:
                data = db_response.json()
                if "tables" in data and len(data["tables"]) > 0:
                    return

        raise RuntimeError(f"Database schema sync timed out for DB {database_id}")

    async def create_card(self, spec: dict[str, Any]) -> int:
        response = await self.client.post(
            f"{self.base_url}/api/card", json=spec, headers=self.headers
        )
        response.raise_for_status()
        return response.json().get("id", 0)

    async def update_card(self, card_id: int, spec: dict[str, Any]) -> None:
        response = await self.client.put(
            f"{self.base_url}/api/card/{card_id}", json=spec, headers=self.headers
        )
        response.raise_for_status()

    async def run_card_query(self, card_id: int) -> dict[str, Any]:
        response = await self.client.post(
            f"{self.base_url}/api/card/{card_id}/query", headers=self.headers
        )
        response.raise_for_status()
        return response.json()

    async def create_dashboard(self, name: str) -> int:
        payload = {"name": name, "description": "Auto-generated by DataForge", "parameters": []}
        response = await self.client.post(
            f"{self.base_url}/api/dashboard", json=payload, headers=self.headers
        )
        response.raise_for_status()
        return response.json().get("id", 0)

    async def set_dashboard_cards(self, dashboard_id: int, card_ids: list[int]) -> None:
        dash_response = await self.client.get(
            f"{self.base_url}/api/dashboard/{dashboard_id}", headers=self.headers
        )
        dash_response.raise_for_status()
        dashboard_data = dash_response.json()
        existing_dashcards = dashboard_data.get("dashcards", [])

        for dc in existing_dashcards:
            await self.client.delete(
                f"{self.base_url}/api/dashboard/{dashboard_id}/cards?dashcardId={dc['id']}",
                headers=self.headers,
            )

        col_width = 6
        row_height = 4
        cards_per_row = 18 // col_width

        for idx, card_id in enumerate(card_ids):
            row = (idx // cards_per_row) * row_height
            col = (idx % cards_per_row) * col_width

            payload = {
                "cardId": card_id,
                "size_x": col_width,
                "size_y": row_height,
                "col": col,
                "row": row,
            }
            add_resp = await self.client.post(
                f"{self.base_url}/api/dashboard/{dashboard_id}/cards",
                json=payload,
                headers=self.headers,
            )
            add_resp.raise_for_status()

    def dashboard_url(self, dashboard_id: int) -> str:
        return f"{self.base_url}/dashboard/{dashboard_id}"
