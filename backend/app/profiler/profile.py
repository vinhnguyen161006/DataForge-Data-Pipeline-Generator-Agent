"""Deterministic statistics over caller-owned, materialized and locked DuckDB tables.

SQL identifiers always pass through quote_identifier; type names and expressions
are generated by this module, never accepted as SQL from the job payload.
"""

from __future__ import annotations

import hashlib
import re
import unicodedata
from itertools import combinations
from typing import TYPE_CHECKING

from app.ingest.filenames import csv_filename
from app.profiler.schemas import (
    ColumnProfile,
    DataProfile,
    KeyCandidate,
    LoadedTable,
    RelationshipCandidate,
    TableProfile,
)

if TYPE_CHECKING:
    from collections.abc import Sequence

    from duckdb import DuckDBPyConnection

MAX_COMPOSITE_COLUMNS = 12
MAX_SAMPLE_CHARACTERS = 160


def quote_identifier(identifier: str) -> str:
    """Quote a nonempty identifier without permitting NUL or SQL interpolation."""
    if not identifier or "\x00" in identifier:
        raise ValueError("SQL identifiers must be nonempty and cannot contain NUL")
    return '"' + identifier.replace('"', '""') + '"'


def table_name_for(filename: str) -> str:
    """Derive a stable portable name, hashing lossy normalization to avoid collisions."""
    stem = csv_filename(filename)[:-4].lower()
    ascii_stem = unicodedata.normalize("NFKD", stem).encode("ascii", "ignore").decode()
    name = re.sub(r"[^a-z0-9_]+", "_", ascii_stem).strip("_") or "source"
    if not name[0].isalpha():
        name = "source_" + name
    if name == stem and len(name) <= 63:
        return name
    return name[:48] + "_" + hashlib.sha256(filename.encode()).hexdigest()[:12]


def _scalar(connection: DuckDBPyConnection, sql: str) -> object:
    row = connection.execute(sql).fetchone()
    if row is None:
        raise RuntimeError("A profile aggregate returned no row")
    return row[0]


def profile_column(
    table: str,
    column: str,
    column_type: str,
    row_count: int,
    *,
    connection: DuckDBPyConnection,
) -> ColumnProfile:
    """Infer types conservatively; preserve zero-prefixed identifiers and bounded samples."""
    relation = quote_identifier(table)
    value = quote_identifier(column)
    stats = connection.execute(
        f"SELECT count({value}), count(DISTINCT {value}), "
        f"count(*) FILTER (WHERE regexp_full_match(trim(CAST({value} AS VARCHAR)), "
        f"'[+-]?0[0-9]+')) FROM {relation}"
    ).fetchone()
    if stats is None:
        raise RuntimeError("Column statistics returned no row")
    present, distinct, leading = (int(item) for item in stats)
    inferred = "VARCHAR"
    expression = value
    if present and not leading:
        for candidate in ("BOOLEAN", "BIGINT", "HUGEINT", "DOUBLE", "DATE", "TIMESTAMP"):
            cast = f"TRY_CAST({value} AS {candidate})"
            condition = f"{cast} IS NOT NULL"
            if candidate == "BOOLEAN":
                condition = f"lower(CAST({value} AS VARCHAR)) IN ('true', 'false')"
            elif candidate in {"BIGINT", "HUGEINT"}:
                condition += (
                    f" AND regexp_full_match(trim(CAST({value} AS VARCHAR)), '[+-]?[0-9]+')"
                )
            elif candidate == "DATE":
                condition += (
                    f" AND regexp_full_match(CAST({value} AS VARCHAR), "
                    "'[0-9]{4}-[0-9]{2}-[0-9]{2}')"
                )
            elif candidate == "DOUBLE":
                condition = (
                    f"isfinite({cast}) AND NOT ("
                    f"regexp_full_match(trim(CAST({value} AS VARCHAR)), '[+-]?[0-9]+') "
                    f"AND TRY_CAST({value} AS HUGEINT) IS NULL)"
                )
            matched = _scalar(
                connection,
                f"SELECT count(*) FILTER (WHERE {condition}) FROM {relation}",
            )
            if matched == present:
                inferred = candidate
                expression = cast
                break
    bounds = connection.execute(
        f"SELECT CAST(min({expression}) AS VARCHAR), CAST(max({expression}) AS VARCHAR) "
        f"FROM {relation}"
    ).fetchone()
    samples = connection.execute(
        f"SELECT left(CAST({value} AS VARCHAR), {MAX_SAMPLE_CHARACTERS}) "
        f"FROM {relation} WHERE {value} IS NOT NULL GROUP BY {value} "
        f"ORDER BY count(*) DESC, CAST({value} AS VARCHAR) LIMIT 5"
    ).fetchall()
    if bounds is None:
        raise RuntimeError("Column bounds returned no row")
    return ColumnProfile(
        name=column,
        inferred_type=inferred,
        row_count=row_count,
        null_ratio=(row_count - present) / row_count if row_count else 0.0,
        distinct_count=distinct,
        min_value=bounds[0],
        max_value=bounds[1],
        sample_values=[str(row[0]) for row in samples],
        has_leading_zeros=bool(leading),
    )


def find_key_candidates(
    table: TableProfile, *, connection: DuckDBPyConnection
) -> list[KeyCandidate]:
    """Report observed nonnull unique keys; examine pairs only when no single key exists."""
    if not table.row_count:
        return []
    singles = [
        KeyCandidate(table=table.name, columns=[column.name], is_unique_in_batch=True, null_count=0)
        for column in table.columns
        if column.null_ratio == 0 and column.distinct_count == table.row_count
    ]
    if singles:
        return singles
    candidates = [column for column in table.columns if column.null_ratio == 0][
        :MAX_COMPOSITE_COLUMNS
    ]
    keys: list[KeyCandidate] = []
    for left, right in combinations(candidates, 2):
        columns = f"({quote_identifier(left.name)}, {quote_identifier(right.name)})"
        distinct = _scalar(
            connection,
            f"SELECT count(DISTINCT {columns}) FROM {quote_identifier(table.name)}",
        )
        if distinct == table.row_count:
            keys.append(
                KeyCandidate(
                    table=table.name,
                    columns=[left.name, right.name],
                    is_unique_in_batch=True,
                    null_count=0,
                )
            )
    return keys


def _matching_columns(
    child: TableProfile, parent: TableProfile, keys: Sequence[KeyCandidate]
) -> list[tuple[list[str], list[str]]]:
    matches: list[tuple[list[str], list[str]]] = []
    parent_names = {column.name.casefold(): column.name for column in parent.columns}
    child_names = {column.name.casefold(): column.name for column in child.columns}
    singular = (
        parent.name[:-3] + "y" if parent.name.endswith("ies") else parent.name.removesuffix("s")
    )
    for name, original in child_names.items():
        if (name.endswith("_id") or name.startswith("id_")) and name in parent_names:
            matches.append(([original], [parent_names[name]]))
        elif name == singular + "_id" and "id" in parent_names:
            matches.append(([original], [parent_names["id"]]))
    for key in keys:
        if (
            key.table == parent.name
            and len(key.columns) > 1
            and all(column.casefold() in child_names for column in key.columns)
        ):
            pair = ([child_names[column.casefold()] for column in key.columns], key.columns)
            if pair not in matches:
                matches.append(pair)
    return matches


def _relationship(
    child: TableProfile,
    parent: TableProfile,
    child_columns: list[str],
    parent_columns: list[str],
    connection: DuckDBPyConnection,
) -> RelationshipCandidate:
    parent_table = quote_identifier(parent.name)
    child_table = quote_identifier(child.name)
    grouped = ", ".join(quote_identifier(column) for column in parent_columns)
    parent_valid = " AND ".join(
        quote_identifier(column) + " IS NOT NULL" for column in parent_columns
    )
    child_valid = " AND ".join(
        "c." + quote_identifier(column) + " IS NOT NULL" for column in child_columns
    )
    join = " AND ".join(
        f"c.{quote_identifier(left)} = p.{quote_identifier(right)}"
        for left, right in zip(child_columns, parent_columns, strict=True)
    )
    matches_name = "__profile_matches"
    while matches_name.casefold() in {column.casefold() for column in parent_columns}:
        matches_name += "_"
    counted = quote_identifier(matches_name)
    sql = (
        f"WITH p AS (SELECT {grouped}, count(*) AS {counted} FROM {parent_table} "
        f"WHERE {parent_valid} GROUP BY {grouped}) "
        f"SELECT count(*), count(p.{counted}), coalesce(max(p.{counted}), 0) "
        f"FROM {child_table} c LEFT JOIN p ON {join} WHERE {child_valid}"
    )
    row = connection.execute(sql).fetchone()
    if row is None:
        raise RuntimeError("Relationship statistics returned no row")
    eligible, matched, maximum = (int(value) for value in row)
    unique = connection.execute(
        f"SELECT count(*), count(DISTINCT ({grouped})), "
        f"count(*) FILTER (WHERE NOT ({parent_valid})) FROM {parent_table}"
    ).fetchone()
    if unique is None:
        raise RuntimeError("Parent key statistics returned no row")
    return RelationshipCandidate(
        child_table=child.name,
        child_columns=child_columns,
        parent_table=parent.name,
        parent_columns=parent_columns,
        match_ratio=matched / eligible if eligible else 0.0,
        orphan_count=eligible - matched,
        parent_key_unique=bool(unique[0] and unique[0] == unique[1] and unique[2] == 0),
        fanout_warning=maximum > 1,
        max_parent_matches=maximum,
    )


def find_relationship_candidates(
    tables: Sequence[TableProfile],
    *,
    connection: DuckDBPyConnection,
    keys: Sequence[KeyCandidate],
) -> list[RelationshipCandidate]:
    """Measure name-based and composite join candidates without asserting constraints."""
    result: list[RelationshipCandidate] = []
    for child in tables:
        for parent in tables:
            if child.name != parent.name:
                for child_columns, parent_columns in _matching_columns(child, parent, keys):
                    result.append(
                        _relationship(child, parent, child_columns, parent_columns, connection)
                    )
    return result


def profile_files(tables: Sequence[LoadedTable], *, connection: DuckDBPyConnection) -> DataProfile:
    """Build a profile on the caller's locked connection, without reopening any source."""
    policy = connection.execute(
        "SELECT current_setting('enable_external_access'), current_setting('lock_configuration')"
    ).fetchone()
    if policy != (False, True):
        raise ValueError("Profiling requires a locked DuckDB connection")
    if not tables or len({table.name.casefold() for table in tables}) != len(tables):
        raise ValueError("Profiling requires distinct materialized tables")
    profiled: list[TableProfile] = []
    keys: list[KeyCandidate] = []
    notes = [
        "Key and relationship candidates are observations, not approved constraints.",
        "Relationship ratios exclude child rows with any NULL join component.",
        "Relationship discovery uses matching *_id names and observed composite keys.",
        "Samples contain at most five values per column, truncated to 160 characters.",
    ]
    for table in tables:
        csv_filename(table.source_file)
        materialized = connection.execute(
            "SELECT count(*) FROM duckdb_tables() WHERE table_name = ? "
            "AND schema_name = 'main' AND database_name = current_database()",
            [table.name],
        ).fetchone()
        if materialized != (1,):
            raise ValueError("Profiling requires a materialized source table")
        row = connection.execute(f"SELECT count(*) FROM {quote_identifier(table.name)}").fetchone()
        if row is None:
            raise RuntimeError("Table statistics returned no row")
        count = int(row[0])
        columns = connection.execute(
            "SELECT column_name, data_type FROM information_schema.columns "
            "WHERE table_schema = 'main' AND table_catalog = current_database() "
            "AND table_name = ? ORDER BY ordinal_position",
            [table.name],
        ).fetchall()
        stats = TableProfile(
            name=table.name,
            source_file=table.source_file,
            row_count=count,
            columns=[
                profile_column(table.name, str(name), str(kind), count, connection=connection)
                for name, kind in columns
            ],
        )
        profiled.append(stats)
        table_keys = find_key_candidates(stats, connection=connection)
        keys.extend(table_keys)
        if (
            not any(len(key.columns) == 1 for key in table_keys)
            and len(stats.columns) > MAX_COMPOSITE_COLUMNS
        ):
            notes.append(
                f"Composite key search for {table.name} examines at most 12 nonnull columns."
            )
    return DataProfile(
        tables=profiled,
        key_candidates=keys,
        relationship_candidates=find_relationship_candidates(
            profiled, connection=connection, keys=keys
        ),
        notes=notes,
    )
